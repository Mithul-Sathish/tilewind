# Builds server/game.js: the same rules engine and match flow the browser runs, wrapped so each online table
# gets its own copy of the game state. Run after build.py's sources change; the browser build is unaffected.
import re
old=open('v2.html').read()
def cut(a,b,src=old):
    i=src.index(a); j=src.index(b,i); return src[i:j]
SEC='/* =========================================================\n   '
names=cut("const HAN_NUM","const C = {")
core=cut(SEC+"HAND ANALYSIS",SEC+"MAIN LOOP")
for f in ['speed','sleep','shuffle','newMatch','setupHand']:
    core=core.replace("function "+f+"(","function "+f+"_v2(",1)
core=core.replace("Math.random()","rnd()")
core=core.replace("diff = settings.difficulty","diff = (p.diff != null ? p.diff : S.diff)")  # a seat can have its own level (mixed tables, and the level test)
core=core.replace("settings.difficulty >= 1","S.diff >= 1")
meta=open('src/meta.js').read()
def grab(start, src):
    i=src.index(start); j=src.index('\n];',i)+3 if src[i:].startswith('const') and '[' in src[i:i+40] else src.index('\n',i)
    return src[i:j]
hashStr=grab('const hashStr', meta)
seat=meta[meta.index('const SEAT = ['):meta.index('];',meta.index('const SEAT = ['))+2]
styles=meta[meta.index('const STYLES = ['):meta.index('];',meta.index('const STYLES = ['))+2]
rnd=meta[meta.index('function rnd(){'):meta.index('\n}\n',meta.index('function rnd(){'))+3]
flow=open('src/flow.js').read()
host=open('server/host.js').read()
stubs = r'''
const window = {}, document = undefined;
const settings = { pace: 'normal', calls: 'standard', difficulty: 1, coach: 0, length: 4, sortStyle: 'suit', autoSort: 'on' };
const profile = { intro: 9, kind: 'old' };
const STAGE = { deal: 3600, land: 420 };   // how long the browsers' deal and tile flight take, so the table never runs ahead of what people see
const V = { resetTypes(){}, deal: () => new Promise(r => setTimeout(r, STAGE.deal)), whenLanded: () => new Promise(r => setTimeout(r, STAGE.land)), retype(){}, pushTo(){}, nudge(){}, sync(){} };
const render = () => NET.push();
const showScreen = () => {}, fpsStart = () => {}, fpsStop = () => {}, snd = () => {}, haptic = () => {}, setTension = () => {}, closeOverlay = () => {};
const questEvent = () => [], save = () => {}, introIdea = async () => {}, recordHand = () => {}, sitting = () => [], rankInfo = () => ({}), paintWin = () => {};
const resultSlip = () => Promise.resolve('next'), netLobbyBack = () => {}, goHome = () => {}, noteNew = () => {}, lift = () => {}, tileHTML = t => tName(t);
const nearMissFor = () => '', nearMiss = () => '', stampWin = () => [], rareReveal = async () => {}, saveResumeNow = () => {}, lessonEvent = undefined;
const dayKey = () => '', weeklySeed = () => 0, RKEY = 'x', load = () => null;
function callStroke(pi, type, ms = 950){ if (S && S.mode === 'net') NET.fx('stroke', { pi, type, ms }); }
'''
import re as _re
defined=set(_re.findall(r'^(?:async )?function (\w+)\(', flow+core, _re.M))|set(_re.findall(r'^(?:const|let) (\w+)', flow+core, _re.M))
keep=[]
for ln in stubs.split('\n'):
    if ln.startswith('const ') and '=' in ln:
        parts=[x.strip() for x in _re.split(r',\s*(?=\w+ = )', ln[6:].rstrip(';'))]
        parts=[x for x in parts if x.split(' =')[0] not in defined]
        ln='const '+', '.join(parts)+';' if parts else ''
    keep.append(ln)
stubs='\n'.join(keep)
body = stubs + names + hashStr + '\n' + seat + '\n' + styles + '\n' + rnd + core + flow + host
out = "/* Generated by build_server.py from the game's own sources. Do not edit by hand. */\nexport function createGame(opts){\n'use strict';\nopts = opts || {};\n" + body + "\nif (opts.fast){ autotest = true; STAGE.deal = 0; STAGE.land = 0; }\nreturn { NET, state: () => S, stop(){ token++; }, window };\n}\n"
open('server/game.js','w').write(out)
print(len(out))
